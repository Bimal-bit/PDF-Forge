import { runPageCommand } from './workspace-helpers';
import { expect, test } from '@playwright/test';
import { downloadPdf, openAdvanced, pageStreams } from './advanced-helpers';

test('linked text flows across pages, recovers, and reflows after page deletion', async ({ page }) => {
  await openAdvanced(page, 2);
  await page.getByRole('button', { name: 'Layout', exact: true }).click();
  await page.getByRole('button', { name: 'Text flow & columns', exact: true }).click();
  const tools = page.getByRole('dialog', { name: 'Text flow & columns' });
  const story = 'STARTWORD A newsletter story flows through linked boxes and keeps the words in their original order. '.repeat(3) + 'ENDTOKEN';
  await tools.getByRole('button', { name: 'Add text box', exact: true }).click();
  await tools.getByLabel('Text box content').fill(story);
  await tools.getByLabel('Text frame width', { exact: true }).fill('180');
  await tools.getByLabel('Text frame height', { exact: true }).fill('44');
  await tools.getByLabel('Text frame y', { exact: true }).fill('450');
  const firstId = await tools.getByLabel('Layout text box').inputValue();
  await tools.getByLabel('Close Text flow & columns').click();
  await page.getByLabel('Go to page 2', { exact: true }).click();
  await page.getByRole('button', { name: 'Text flow & columns', exact: true }).click();
  await tools.getByRole('button', { name: 'Add text box', exact: true }).click();
  await tools.getByLabel('Text frame width', { exact: true }).fill('180');
  await tools.getByLabel('Text frame height', { exact: true }).fill('300');
  const secondId = await tools.getByLabel('Layout text box').inputValue();
  await tools.getByLabel('Layout text box').selectOption(firstId);
  await tools.getByLabel('Continue into text box').selectOption(secondId);
  await tools.getByRole('button', { name: 'Link text boxes', exact: true }).click();
  await tools.getByLabel('Close Text flow & columns').click();
  await expect(page.locator('.flow-text-object')).toHaveCount(2);
  await page.getByLabel('Find text in document').fill('ENDTOKEN');
  await expect(page.locator('.search-box')).toContainText('Go to page 2');
  const pending = page.waitForEvent('download');
  await page.getByLabel('Export PDF', { exact: true }).click();
  const pdf = await downloadPdf(await pending);
  expect(pageStreams(pdf, 1)).toContain('454E44544F4B454E');
  await expect(page.getByRole('status')).toHaveText('Saved locally', { timeout: 8000 });
  await page.reload();
  await expect(page.locator('.flow-text-object')).toHaveCount(2);
  await page.getByLabel('Go to page 1', { exact: true }).click();
  await page.getByRole('button', { name: 'Tools', exact: true }).click();
  await runPageCommand(page, 'Delete page');
  await expect(page.locator('.flow-text-object')).toHaveCount(1);
  await page.getByLabel('Find text in document').fill('STARTWORD');
  await expect(page.locator('.search-box')).toContainText('3 matches');
  const afterDelete = page.waitForEvent('download');
  await page.getByLabel('Export PDF', { exact: true }).click();
  const surviving = await downloadPdf(await afterDelete);
  expect(surviving.getPageCount()).toBe(1);
  expect(pageStreams(surviving)).toContain('454E44544F4B454E');
  expect(pageStreams(surviving)).toContain('5354415254574F5244');
});

test('columns and drop caps share their geometry with vector export', async ({ page }) => {
  await openAdvanced(page);
  await page.getByRole('button', { name: 'Layout', exact: true }).click();
  await page.getByRole('button', { name: 'Text flow & columns', exact: true }).click();
  const tools = page.getByRole('dialog', { name: 'Text flow & columns' });
  await tools.getByRole('button', { name: 'Add text box', exact: true }).click();
  await tools.getByLabel('Text box content').fill('A newsletter needs clear columns and a large opening letter. This text continues through all three columns with consistent spacing and useful paragraph layout.');
  await tools.getByLabel('Text frame width', { exact: true }).fill('360');
  await tools.getByLabel('Text frame height', { exact: true }).fill('200');
  await tools.getByLabel('Text columns').selectOption('3');
  await tools.getByLabel('Drop cap', { exact: true }).selectOption('3');
  await tools.getByLabel('Close Text flow & columns').click();
  const glyphs = page.locator('.flow-text-object text');
  const capSize = Number(await glyphs.first().getAttribute('font-size'));
  expect(capSize).toBeGreaterThan(40);
  expect(new Set(await glyphs.evaluateAll((elements) => elements.map((element) => Math.floor(Number(element.getAttribute('x')) / 126)))).size).toBe(3);
  const pending = page.waitForEvent('download');
  await page.getByLabel('Export PDF', { exact: true }).click();
  const streams = pageStreams(await downloadPdf(await pending));
  expect(streams).toContain(String(capSize).slice(0, 8));
  expect(streams).toContain(' Tj');
  await page.getByLabel('Undo', { exact: true }).click();
  expect(Number(await page.locator('.flow-text-object text').first().getAttribute('font-size'))).toBe(12);
});

