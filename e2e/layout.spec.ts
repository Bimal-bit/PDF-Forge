test('flowchart connectors follow pointer and keyboard movement and cascade with deletion', async ({ page }) => {
  await openAdvanced(page);
  await page.getByRole('button', { name: 'Layout', exact: true }).click();
  await page.getByRole('button', { name: 'Insert', exact: true }).click(); await page.getByRole('button', { name: 'Shapes & connectors', exact: true }).click();
  const tools = page.getByRole('dialog', { name: 'Shapes & connectors' });
  await tools.getByRole('button', { name: 'Add flowchart shape', exact: true }).click();
  await tools.getByLabel('Shape label').fill('Start');
  await tools.getByLabel('Shape x', { exact: true }).fill('40');
  await tools.getByLabel('Shape y', { exact: true }).fill('450');
  await tools.getByLabel('New flowchart shape').selectOption('diamond');
  await tools.getByRole('button', { name: 'Add flowchart shape', exact: true }).click();
  await tools.getByLabel('Shape label').fill('Check');
  await tools.getByLabel('Shape x', { exact: true }).fill('280');
  await tools.getByLabel('Shape y', { exact: true }).fill('300');
  await tools.getByRole('button', { name: 'Connect shapes', exact: true }).click();
  await tools.getByLabel('Close Shapes & connectors').click();
  const connector = page.locator('[data-connector]');
  const initial = await connector.getAttribute('d');
  const shape = page.getByRole('button', { name: 'Move shape Check', exact: true });
  await shape.scrollIntoViewIfNeeded();
  const box = (await shape.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 30, box.y + box.height / 2 + 20);
  await page.mouse.up();
  await expect(connector).not.toHaveAttribute('d', initial!);
  await page.getByLabel('Undo', { exact: true }).click();
  await expect(connector).toHaveAttribute('d', initial!);
  await shape.focus(); await page.keyboard.press('ArrowRight');
  await expect(connector).not.toHaveAttribute('d', initial!);
  const pending = page.waitForEvent('download');
  await page.getByLabel('Export PDF', { exact: true }).click();
  const streams = pageStreams(await downloadPdf(await pending));
  expect(streams).toContain('436865636B');
  expect(streams).toContain(' l');
  await page.getByRole('button', { name: 'Insert', exact: true }).click(); await page.getByRole('button', { name: 'Shapes & connectors', exact: true }).click();
  await tools.getByRole('button', { name: 'Delete selected shape', exact: true }).click();
  await tools.getByLabel('Close Shapes & connectors').click();
  await expect(connector).toHaveCount(0);
  await page.getByLabel('Undo', { exact: true }).click();
  await expect(connector).toHaveCount(1);
  await page.getByRole('button', { name: 'Tools', exact: true }).click();
  await runPageCommand(page, 'Rotate page');
  await page.getByRole('button', { name: 'View', exact: true }).click();
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  await shape.scrollIntoViewIfNeeded();
  const rotated = (await shape.boundingBox())!;
  await page.mouse.move(rotated.x + rotated.width / 2, rotated.y + rotated.height / 2);
  await page.mouse.down();
  await page.mouse.move(rotated.x + rotated.width / 2 + 20, rotated.y + rotated.height / 2 + 30);
  await page.mouse.up();
  await expect.poll(async () => (await shape.boundingBox())!.x).toBeCloseTo(rotated.x + 20, 0);
  await expect.poll(async () => (await shape.boundingBox())!.y).toBeCloseTo(rotated.y + 30, 0);
});

test('moving replacement text preserves its cover at the source position', async ({ page }) => {
  await openAdvanced(page, 1, 'Source paragraph');
  await page.locator('.text-layer span').filter({ hasText: 'Source paragraph' }).dblclick();
  await page.getByLabel('Edit PDF text').fill('Moved replacement');
  await page.getByLabel('Find text in document').click();
  const cover = page.locator('.text-block-object > span').first();
  const original = await cover.evaluate((element) => ({ left: getComputedStyle(element).left, bottom: getComputedStyle(element).bottom }));
  await page.getByRole('button', { name: 'Layout', exact: true }).click();
  await page.getByRole('button', { name: 'Text flow & columns', exact: true }).click();
  const tools = page.getByRole('dialog', { name: 'Text flow & columns' });
  await tools.getByLabel('Text frame x', { exact: true }).fill('200');
  await tools.getByLabel('Text frame y', { exact: true }).fill('400');
  await tools.getByLabel('Close Text flow & columns').click();
  await expect(cover).toHaveCSS('left', original.left);
  await expect(cover).toHaveCSS('bottom', original.bottom);
  await expect(page.locator('.text-object')).toHaveCSS('left', '200px');
  await page.getByLabel('Find text in document').fill('Source paragraph');
  await expect(page.locator('.search-box')).toContainText('0 matches');
  const pending = page.waitForEvent('download');
  await page.getByLabel('Export PDF', { exact: true }).click();
  expect(pageStreams(await downloadPdf(await pending))).toContain(`${parseFloat(original.left)} ${parseFloat(original.bottom)}`);
});
